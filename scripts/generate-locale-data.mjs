/**
 * Builds src/i18n/currencies.ts: every currency in circulation, with its name
 * in each app language and how many decimals it uses. Names come from Node's
 * built-in ICU data, so the app doesn't need full Intl support at runtime.
 *
 * Also writes src/i18n/countries.ts (country names for the phone picker).
 *
 * Usage: node scripts/generate-locale-data.mjs
 */
import { writeFileSync } from 'node:fs';

// ISO 4217 currencies in use (October 2026). Bulgaria moved to the euro in 2026
// and Curaçao/Sint Maarten to XCG in 2025, so BGN and ANG are left out.
const CODES = `AED AFN ALL AMD AOA ARS AUD AWG AZN BAM BBD BDT BHD BIF BMD BND BOB BRL BSD BTN BWP BYN BZD
CAD CDF CHF CLP CNY COP CRC CUP CVE CZK DJF DKK DOP DZD EGP ERN ETB EUR FJD FKP GBP GEL GHS GIP GMD GNF
GTQ GYD HKD HNL HTG HUF IDR ILS INR IQD IRR ISK JMD JOD JPY KES KGS KHR KMF KPW KRW KWD KYD KZT LAK LBP
LKR LRD LSL LYD MAD MDL MGA MKD MMK MNT MOP MRU MUR MVR MWK MXN MYR MZN NAD NGN NIO NOK NPR NZD OMR PAB
PEN PGK PHP PKR PLN PYG QAR RON RSD RUB RWF SAR SBD SCR SDG SEK SGD SHP SLE SOS SRD SSP STN SYP SZL THB
TJS TMT TND TOP TRY TTD TWD TZS UAH UGX USD UYU UZS VES VND VUV WST XAF XCD XCG XOF XPF YER ZAR ZMW ZWG`
  .split(/\s+/)
  .filter(Boolean);

const LANGS = ['en', 'fr', 'es', 'hi'];
const names = Object.fromEntries(LANGS.map((l) => [l, new Intl.DisplayNames([l], { type: 'currency' })]));

const rows = CODES.map((code) => {
  const digits = new Intl.NumberFormat('en', { style: 'currency', currency: code }).resolvedOptions().maximumFractionDigits;
  const n = LANGS.map((l) => {
    const name = names[l].of(code);
    // ICU returns the code itself when it has no name; fall back to English.
    return name && name !== code ? name : names.en.of(code);
  });
  return { code, digits, n };
});

const missing = rows.filter((r) => r.n[0] === r.code).map((r) => r.code);
if (missing.length) console.warn('No English name for:', missing.join(', '));

const body = rows
  .map((r) => `  ['${r.code}', ${r.digits}, ${r.n.map((s) => JSON.stringify(s)).join(', ')}],`)
  .join('\n');

writeFileSync(
  'src/i18n/currencies.ts',
  `/**
 * Every currency in circulation: [code, decimals, English, French, Spanish, Hindi].
 * Generated by scripts/generate-locale-data.mjs — don't edit by hand.
 */

export const CURRENCY_TABLE: ReadonlyArray<readonly [string, number, string, string, string, string]> = [
${body}
];
`,
);
console.log(`✓ src/i18n/currencies.ts (${rows.length} currencies)`);

// ─── Country names for the phone number picker ──────────────────────────────
const { getCountries } = await import('libphonenumber-js');
const regionNames = Object.fromEntries(LANGS.map((l) => [l, new Intl.DisplayNames([l], { type: 'region' })]));
const countries = getCountries().map((c) => {
  const n = LANGS.map((l) => {
    const name = regionNames[l].of(c);
    return name && name !== c ? name : regionNames.en.of(c) ?? c;
  });
  return `  ['${c}', ${n.map((s) => JSON.stringify(s)).join(', ')}],`;
});
writeFileSync(
  'src/i18n/countries.ts',
  `/**
 * Country names for the phone picker: [ISO code, English, French, Spanish, Hindi].
 * Generated by scripts/generate-locale-data.mjs — don't edit by hand.
 */

export const COUNTRY_TABLE: ReadonlyArray<readonly [string, string, string, string, string]> = [
${countries.join('\n')}
];
`,
);
console.log(`✓ src/i18n/countries.ts (${countries.length} countries)`);
